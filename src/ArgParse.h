/// logic for parsing the arguments such as --compile etc.
/// this header should be only included by main and noone else.
#pragma once

#include "Diagnostics.h"

#include <cstdint>
#include <cstring>
#include <fstream>
#include <string>

using flag_t = uint32_t;

enum Flags
{
    INVALID = 1 << 0,
    TOKENIZE = 1 << 1,
    PARSE = 1 << 2,
    PRINT_AST = 1 << 3,
    COMPILE = 1 << 4,
    OPTIMIZE = 1 << 5,
    OPTIMIZE_RUN_TIME = 1 << 6 | OPTIMIZE | COMPILE,
    OPTIMIZE_COMPILE_TIME = 1 << 7 | COMPILE,
};

struct Arguments
{
    flag_t flags = 0;
    std::string filename;
};

// we do some synthesized dragon magic
// in order to differentiate the flags

constexpr auto flag0 = "--print-ast";
constexpr auto flag1 = "--tokenize";
constexpr auto flag2 = "--optimize";
constexpr auto flag3 = "--parse";
constexpr auto flag4 = "--optimize-compile-time";
constexpr auto flag5 = "--optimize-run-time";
constexpr auto flag6 = "--compile";

constexpr const char* LUT[] = {
    flag0, flag1, flag2, flag3, flag4, flag5, flag6,
};

constexpr uint8_t FLAG[] = {
    PRINT_AST, TOKENIZE, OPTIMIZE, PARSE, OPTIMIZE_COMPILE_TIME, OPTIMIZE_RUN_TIME, COMPILE,
};

constexpr uint8_t hash8(const uint8_t* str)
{
    uint8_t val = 0x10;

    for (; *str; ++str)
        val ^= *str;

    return val % 7;
}

static flag_t parseFlag(const char* argument)
{
    uint8_t index = hash8((const uint8_t*)argument);

    const char* expected = LUT[index];

    if (strcmp(argument, expected) == 0)
        return FLAG[index];

    return Flags::INVALID;
}

static Arguments parseArguments(int argc, const char** argv)
{
    Arguments res;

    if (argc == 1)
    {
        diagnostics::error("not enough command line arguments!");
    }

    for (int i = 1; i < argc; ++i)
    {
        const char* argument = argv[i];

        if (argument[0] == '-')
        {
            res.flags |= parseFlag(argument);
        }
        else
        {
            res.filename = std::string(argument);
        }
    }

    if (res.flags & Flags::INVALID || res.filename.empty())
    {
        diagnostics::error("Received invalid arguments!");
    }

    if (res.flags == 0)
    {
        res.flags |= Flags::COMPILE;
        res.flags |= Flags::OPTIMIZE;
    }

    return res;
}

static void readFile(const std::string& filename, std::string& content)
{
    std::ifstream file(filename, std::ios::binary | std::ios::ate);

    if (!file)
    {
        std::cerr << "File could not be read: " << filename << std::endl;
        exit(EXIT_FAILURE);
    }

    // size of the file, so we can read everything in one go
    const std::streamsize size = file.tellg();
    content.resize(size + 1);

    file.seekg(0, std::ios::beg);
    if (!file.read(&content[0], size))
    {
        file.close();
        std::cerr << "Error reading the file!" << std::endl;
        exit(EXIT_FAILURE);
    }

    file.close();
}

// generated by ChatGPT
static const std::string getOutputFilename(std::string_view filepath)
{
    // Find the last '/' or '\' to isolate the filename
    size_t lastSlash = filepath.find_last_of("/\\");
    if (lastSlash == std::string_view::npos)
        lastSlash = 0; // No slash found, start from beginning
    else
        lastSlash += 1; // Move past the slash

    // Find the last '.' to remove the extension
    size_t lastDot = filepath.find_last_of('.');
    if (lastDot == std::string_view::npos || lastDot < lastSlash)
        lastDot = filepath.size(); // No dot or dot is part of the path

    // Extract the substring for the filename without extension
    return std::string(filepath.substr(lastSlash, lastDot - lastSlash)) + ".ll";
}
