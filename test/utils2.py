import difflib

def prettify(line, colors=True):
    """
    colors the given line depending on its prefix.
    intended use are lines generated by diff tool
    """

    if line.startswith("? "):
        return "  " + line[2:]

    elif colors and line.startswith("- "):
        return "\x1b[1;31m" + line.strip() + "\x1b[0m\n"
    elif colors and line.startswith("+ "):
        return "\x1b[1;32m" + line.strip() + "\x1b[0m\n"

    else:
        return line


def compare_outputs(actual: str, expected: str, colors=True):
    """
    compares two (multiline) strings and produces a nicely looking
    string which indicates the differences and chops of similarities
    """

    if actual == expected:
        return None

    results = difflib.Differ().compare(
        actual.splitlines(keepends=True),
        expected.splitlines(keepends=True))

    results = [prettify(result) for result in results]
    return results
